WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USER_TABLES WHERE TABLE_NAME = 'VACUNAS';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'[
CREATE TABLE VACUNAS (
    ID_VACUNA NUMBER(10) DEFAULT SEQ_PRODUCTOS.NEXTVAL PRIMARY KEY,
    ID_PROVEEDOR NUMBER(10) REFERENCES PROVEEDORES (ID_PROVEEDOR),
    SKU VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    NOMBRE_VACUNA VARCHAR2(120 CHAR) NOT NULL,
    STOCK NUMBER(10) DEFAULT 0 NOT NULL CHECK (STOCK >= 0),
    STOCK_MINIMO NUMBER(10) DEFAULT 0 NOT NULL CHECK (STOCK_MINIMO >= 0),
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0, 1))
)
        ]';
    END IF;
END;
/

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_VACUNACIONES_VACUNAS';
    IF v_existe = 0 THEN
        UPDATE PRODUCTOS p SET ES_VACUNA = 1
         WHERE ES_VACUNA = 0
           AND (p.SKU IN ('VAC-RAB-001', 'VAC-OCT-002', 'VAC-TRI-003') OR EXISTS (
            SELECT 1 FROM VACUNACIONES v WHERE v.ID_PRODUCTO = p.ID_PRODUCTO
         ));

        INSERT INTO VACUNAS (ID_VACUNA, ID_PROVEEDOR, SKU, NOMBRE_VACUNA, STOCK, STOCK_MINIMO, ACTIVO)
        SELECT p.ID_PRODUCTO, p.ID_PROVEEDOR, p.SKU, p.NOMBRE_PRODUCTO, p.STOCK, p.STOCK_MINIMO, p.ACTIVO
          FROM PRODUCTOS p
         WHERE p.ES_VACUNA = 1
           AND NOT EXISTS (SELECT 1 FROM VACUNAS v WHERE v.ID_VACUNA = p.ID_PRODUCTO);
        EXECUTE IMMEDIATE 'ALTER TABLE VACUNACIONES ADD CONSTRAINT FK_VACUNACIONES_VACUNAS
            FOREIGN KEY (ID_PRODUCTO) REFERENCES VACUNAS (ID_VACUNA)';
    END IF;

    SELECT COUNT(*) INTO v_existe FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_VACUNACIONES_PRODUCTOS';
    IF v_existe = 1 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE VACUNACIONES DROP CONSTRAINT FK_VACUNACIONES_PRODUCTOS';
    END IF;
END;
