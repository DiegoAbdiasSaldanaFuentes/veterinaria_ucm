CREATE SEQUENCE SEQ_PROVEEDORES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_PRODUCTOS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_VENTAS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_DETALLE_VENTAS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_SERVICIOS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_BLOQUES_AGENDA START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_CITAS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_FICHAS_CLINICAS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_RECETAS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_VACUNACIONES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;

CREATE TABLE PROVEEDORES (
    ID_PROVEEDOR NUMBER(10) DEFAULT SEQ_PROVEEDORES.NEXTVAL,
    RAZON_SOCIAL VARCHAR2(150 CHAR) CONSTRAINT NN_PROVEEDORES_RAZON NOT NULL,
    RUT VARCHAR2(10 CHAR),
    TELEFONO VARCHAR2(20 CHAR),
    CORREO VARCHAR2(254 CHAR),
    CONSTRAINT PK_PROVEEDORES PRIMARY KEY (ID_PROVEEDOR),
    CONSTRAINT UK_PROVEEDORES_RUT UNIQUE (RUT),
    CONSTRAINT CK_PROVEEDORES_RUT CHECK (REGEXP_LIKE(RUT, '^[0-9]{1,8}-[0-9K]$', 'c'))
);

CREATE TABLE PRODUCTOS (
    ID_PRODUCTO NUMBER(10) DEFAULT SEQ_PRODUCTOS.NEXTVAL,
    ID_PROVEEDOR NUMBER(10),
    SKU VARCHAR2(40 CHAR) CONSTRAINT NN_PRODUCTOS_SKU NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120 CHAR) CONSTRAINT NN_PRODUCTOS_NOMBRE NOT NULL,
    PRECIO_UNITARIO NUMBER(12) CONSTRAINT NN_PRODUCTOS_PRECIO NOT NULL,
    STOCK NUMBER(10) DEFAULT 0 CONSTRAINT NN_PRODUCTOS_STOCK NOT NULL,
    STOCK_MINIMO NUMBER(10) DEFAULT 0 CONSTRAINT NN_PRODUCTOS_STOCK_MIN NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 CONSTRAINT NN_PRODUCTOS_ACTIVO NOT NULL,
    ES_VACUNA NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT UK_PRODUCTOS_SKU UNIQUE (SKU),
    CONSTRAINT FK_PRODUCTOS_PROVEEDORES FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES (ID_PROVEEDOR),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0 AND STOCK_MINIMO >= 0),
    CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_PRODUCTOS_ES_VACUNA CHECK (ES_VACUNA IN (0, 1))
);

CREATE TABLE VENTAS (
    ID_VENTA NUMBER(10) DEFAULT SEQ_VENTAS.NEXTVAL,
    ID_USUARIO NUMBER(10) CONSTRAINT NN_VENTAS_USUARIO NOT NULL,
    ID_CLIENTE NUMBER(10),
    FECHA_VENTA TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP CONSTRAINT NN_VENTAS_FECHA NOT NULL,
    ESTADO VARCHAR2(10 CHAR) DEFAULT 'REGISTRADA' CONSTRAINT NN_VENTAS_ESTADO NOT NULL,
    CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VENTAS_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT FK_VENTAS_CLIENTES FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES (ID_CLIENTE),
    CONSTRAINT CK_VENTAS_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'ANULADA'))
);

CREATE TABLE DETALLE_VENTAS (
    ID_DETALLE_VENTA NUMBER(10) DEFAULT SEQ_DETALLE_VENTAS.NEXTVAL,
    ID_VENTA NUMBER(10) CONSTRAINT NN_DETALLE_VENTAS_VENTA NOT NULL,
    ID_PRODUCTO NUMBER(10) CONSTRAINT NN_DETALLE_VENTAS_PRODUCTO NOT NULL,
    CANTIDAD NUMBER(10) CONSTRAINT NN_DETALLE_VENTAS_CANTIDAD NOT NULL,
    PRECIO_UNITARIO NUMBER(12) CONSTRAINT NN_DETALLE_VENTAS_PRECIO NOT NULL,
    CONSTRAINT PK_DETALLE_VENTAS PRIMARY KEY (ID_DETALLE_VENTA),
    CONSTRAINT UK_DETALLE_VENTAS_PRODUCTO UNIQUE (ID_VENTA, ID_PRODUCTO),
    CONSTRAINT FK_DETALLE_VENTAS_VENTAS FOREIGN KEY (ID_VENTA) REFERENCES VENTAS (ID_VENTA),
    CONSTRAINT FK_DETALLE_VENTAS_PRODUCTOS FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS (ID_PRODUCTO),
    CONSTRAINT CK_DETALLE_VENTAS_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_VENTAS_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

CREATE TABLE SERVICIOS (
    ID_SERVICIO NUMBER(10) DEFAULT SEQ_SERVICIOS.NEXTVAL,
    NOMBRE_SERVICIO VARCHAR2(120 CHAR) CONSTRAINT NN_SERVICIOS_NOMBRE NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 CONSTRAINT NN_SERVICIOS_ACTIVO NOT NULL,
    CONSTRAINT PK_SERVICIOS PRIMARY KEY (ID_SERVICIO),
    CONSTRAINT UK_SERVICIOS_NOMBRE UNIQUE (NOMBRE_SERVICIO),
    CONSTRAINT CK_SERVICIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE BLOQUES_AGENDA (
    ID_BLOQUE NUMBER(10) DEFAULT SEQ_BLOQUES_AGENDA.NEXTVAL,
    ID_VETERINARIO NUMBER(10) CONSTRAINT NN_BLOQUES_VETERINARIO NOT NULL,
    FECHA_HORA_INICIO DATE CONSTRAINT NN_BLOQUES_INICIO NOT NULL,
    HABILITADO NUMBER(1) DEFAULT 1 CONSTRAINT NN_BLOQUES_HABILITADO NOT NULL,
    CONSTRAINT PK_BLOQUES_AGENDA PRIMARY KEY (ID_BLOQUE),
    CONSTRAINT UK_BLOQUES_VET_INICIO UNIQUE (ID_VETERINARIO, FECHA_HORA_INICIO),
    CONSTRAINT FK_BLOQUES_AGENDA_USUARIOS FOREIGN KEY (ID_VETERINARIO) REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT CK_BLOQUES_HABILITADO CHECK (HABILITADO IN (0, 1)),
    CONSTRAINT CK_BLOQUES_MEDIA_HORA CHECK (
        FECHA_HORA_INICIO = TRUNC(FECHA_HORA_INICIO, 'HH24')
        OR FECHA_HORA_INICIO = TRUNC(FECHA_HORA_INICIO, 'HH24') + 1 / 48
    )
);

CREATE TABLE CITAS (
    ID_CITA NUMBER(10) DEFAULT SEQ_CITAS.NEXTVAL,
    ID_BLOQUE NUMBER(10) CONSTRAINT NN_CITAS_BLOQUE NOT NULL,
    ID_PACIENTE NUMBER(10) CONSTRAINT NN_CITAS_PACIENTE NOT NULL,
    ID_SERVICIO NUMBER(10) CONSTRAINT NN_CITAS_SERVICIO NOT NULL,
    ESTADO VARCHAR2(12 CHAR) DEFAULT 'RESERVADA' CONSTRAINT NN_CITAS_ESTADO NOT NULL,
    MOTIVO VARCHAR2(500 CHAR),
    CONSTRAINT PK_CITAS PRIMARY KEY (ID_CITA),
    CONSTRAINT FK_CITAS_BLOQUES FOREIGN KEY (ID_BLOQUE) REFERENCES BLOQUES_AGENDA (ID_BLOQUE),
    CONSTRAINT FK_CITAS_PACIENTES FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_CITAS_SERVICIOS FOREIGN KEY (ID_SERVICIO) REFERENCES SERVICIOS (ID_SERVICIO),
    CONSTRAINT CK_CITAS_ESTADO CHECK (ESTADO IN ('RESERVADA', 'CANCELADA', 'ATENDIDA', 'NO_ASISTIO'))
);

-- Las citas canceladas conservan su bloque en el historial y liberan su cupo.
CREATE UNIQUE INDEX UX_CITAS_BLOQUE_OCUPADO
    ON CITAS (CASE WHEN ESTADO <> 'CANCELADA' THEN ID_BLOQUE END);

CREATE TABLE FICHAS_CLINICAS (
    ID_FICHA NUMBER(10) DEFAULT SEQ_FICHAS_CLINICAS.NEXTVAL,
    ID_CITA NUMBER(10) CONSTRAINT NN_FICHAS_CITA NOT NULL,
    DIAGNOSTICO VARCHAR2(1000 CHAR),
    OBSERVACIONES VARCHAR2(1000 CHAR),
    CONSTRAINT PK_FICHAS_CLINICAS PRIMARY KEY (ID_FICHA),
    CONSTRAINT UK_FICHAS_CITA UNIQUE (ID_CITA),
    CONSTRAINT FK_FICHAS_CLINICAS_CITAS FOREIGN KEY (ID_CITA) REFERENCES CITAS (ID_CITA)
);

CREATE TABLE RECETAS (
    ID_RECETA NUMBER(10) DEFAULT SEQ_RECETAS.NEXTVAL,
    ID_FICHA NUMBER(10) CONSTRAINT NN_RECETAS_FICHA NOT NULL,
    ID_PRODUCTO NUMBER(10) CONSTRAINT NN_RECETAS_PRODUCTO NOT NULL,
    INDICACIONES VARCHAR2(500 CHAR) CONSTRAINT NN_RECETAS_INDICACIONES NOT NULL,
    CONSTRAINT PK_RECETAS PRIMARY KEY (ID_RECETA),
    CONSTRAINT FK_RECETAS_FICHAS FOREIGN KEY (ID_FICHA) REFERENCES FICHAS_CLINICAS (ID_FICHA),
    CONSTRAINT FK_RECETAS_PRODUCTOS FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS (ID_PRODUCTO)
);

CREATE TABLE VACUNAS (
    ID_VACUNA NUMBER(10) DEFAULT SEQ_PRODUCTOS.NEXTVAL PRIMARY KEY,
    ID_PROVEEDOR NUMBER(10) REFERENCES PROVEEDORES (ID_PROVEEDOR),
    SKU VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    NOMBRE_VACUNA VARCHAR2(120 CHAR) NOT NULL,
    STOCK NUMBER(10) DEFAULT 0 NOT NULL CHECK (STOCK >= 0),
    STOCK_MINIMO NUMBER(10) DEFAULT 0 NOT NULL CHECK (STOCK_MINIMO >= 0),
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE VACUNACIONES (
    ID_VACUNACION NUMBER(10) DEFAULT SEQ_VACUNACIONES.NEXTVAL,
    ID_PACIENTE NUMBER(10) CONSTRAINT NN_VACUNACIONES_PACIENTE NOT NULL,
    ID_PRODUCTO NUMBER(10) CONSTRAINT NN_VACUNACIONES_PRODUCTO NOT NULL,
    ID_USUARIO NUMBER(10) CONSTRAINT NN_VACUNACIONES_USUARIO NOT NULL,
    FECHA_APLICACION DATE CONSTRAINT NN_VACUNACIONES_APLICACION NOT NULL,
    FECHA_PROXIMA_DOSIS DATE CONSTRAINT NN_VACUNACIONES_PROXIMA NOT NULL,
    OBSERVACIONES VARCHAR2(500 CHAR),
    ESTADO NUMBER(1) DEFAULT 0 CONSTRAINT NN_VACUNACIONES_ESTADO NOT NULL,
    CONSTRAINT PK_VACUNACIONES PRIMARY KEY (ID_VACUNACION),
    CONSTRAINT FK_VACUNACIONES_PACIENTES
        FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_VACUNACIONES_VACUNAS
        FOREIGN KEY (ID_PRODUCTO) REFERENCES VACUNAS (ID_VACUNA),
    CONSTRAINT FK_VACUNACIONES_USUARIOS
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT CK_VACUNACIONES_ESTADO CHECK (ESTADO IN (0, 1)),
    CONSTRAINT CK_VACUNACIONES_FECHAS CHECK (FECHA_PROXIMA_DOSIS > FECHA_APLICACION)
);

COMMENT ON COLUMN VACUNACIONES.ESTADO IS
    'Estado del refuerzo programado: 0 = pendiente, 1 = aplicado.';

CREATE INDEX IX_PRODUCTOS_PROVEEDOR ON PRODUCTOS (ID_PROVEEDOR);
CREATE INDEX IX_VENTAS_USUARIO ON VENTAS (ID_USUARIO);
CREATE INDEX IX_VENTAS_CLIENTE ON VENTAS (ID_CLIENTE);
CREATE INDEX IX_DET_VENTAS_PRODUCTO ON DETALLE_VENTAS (ID_PRODUCTO);
CREATE INDEX IX_CITAS_BLOQUE ON CITAS (ID_BLOQUE);
CREATE INDEX IX_CITAS_PACIENTE ON CITAS (ID_PACIENTE);
CREATE INDEX IX_CITAS_SERVICIO ON CITAS (ID_SERVICIO);
CREATE INDEX IX_RECETAS_FICHA ON RECETAS (ID_FICHA);
CREATE INDEX IX_RECETAS_PRODUCTO ON RECETAS (ID_PRODUCTO);



