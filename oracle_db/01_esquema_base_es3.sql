CREATE SEQUENCE SEQ_ROLES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_USUARIOS START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_CLIENTES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_ESPECIES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;
CREATE SEQUENCE SEQ_PACIENTES START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE;

CREATE TABLE ROLES (
    ID_ROL NUMBER(10) DEFAULT SEQ_ROLES.NEXTVAL,
    NOMBRE_ROL VARCHAR2(50 CHAR) CONSTRAINT NN_ROLES_NOMBRE NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
    CONSTRAINT UK_ROLES_NOMBRE UNIQUE (NOMBRE_ROL)
);

CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER(10) DEFAULT SEQ_USUARIOS.NEXTVAL,
    ID_ROL NUMBER(10) CONSTRAINT NN_USUARIOS_ROL NOT NULL,
    NOMBRE_USUARIO VARCHAR2(50 CHAR) CONSTRAINT NN_USUARIOS_NOMBRE_USUARIO NOT NULL,
    CLAVE_HASH VARCHAR2(255 CHAR) CONSTRAINT NN_USUARIOS_CLAVE_HASH NOT NULL,
    NOMBRES VARCHAR2(80 CHAR) CONSTRAINT NN_USUARIOS_NOMBRES NOT NULL,
    APELLIDOS VARCHAR2(100 CHAR) CONSTRAINT NN_USUARIOS_APELLIDOS NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 CONSTRAINT NN_USUARIOS_ACTIVO NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIOS_NOMBRE_USUARIO UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT FK_USUARIOS_ROLES FOREIGN KEY (ID_ROL) REFERENCES ROLES (ID_ROL),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE CLIENTES (
    ID_CLIENTE NUMBER(10) DEFAULT SEQ_CLIENTES.NEXTVAL,
    RUT VARCHAR2(10 CHAR),
    NOMBRES VARCHAR2(80 CHAR) CONSTRAINT NN_CLIENTES_NOMBRES NOT NULL,
    APELLIDOS VARCHAR2(100 CHAR) CONSTRAINT NN_CLIENTES_APELLIDOS NOT NULL,
    TELEFONO VARCHAR2(20 CHAR),
    CORREO VARCHAR2(254 CHAR),
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UK_CLIENTES_RUT UNIQUE (RUT),
    CONSTRAINT CK_CLIENTES_RUT CHECK (REGEXP_LIKE(RUT, '^[0-9]{1,8}-[0-9K]$', 'c'))
);

CREATE TABLE ESPECIES (
    ID_ESPECIE NUMBER(10) DEFAULT SEQ_ESPECIES.NEXTVAL,
    NOMBRE_ESPECIE VARCHAR2(60 CHAR) CONSTRAINT NN_ESPECIES_NOMBRE NOT NULL,
    CONSTRAINT PK_ESPECIES PRIMARY KEY (ID_ESPECIE),
    CONSTRAINT UK_ESPECIES_NOMBRE UNIQUE (NOMBRE_ESPECIE)
);

CREATE TABLE PACIENTES (
    ID_PACIENTE NUMBER(10) DEFAULT SEQ_PACIENTES.NEXTVAL,
    ID_CLIENTE NUMBER(10) CONSTRAINT NN_PACIENTES_CLIENTE NOT NULL,
    ID_ESPECIE NUMBER(10) CONSTRAINT NN_PACIENTES_ESPECIE NOT NULL,
    NOMBRE_PACIENTE VARCHAR2(80 CHAR) CONSTRAINT NN_PACIENTES_NOMBRE NOT NULL,
    FECHA_NACIMIENTO DATE,
    CONSTRAINT PK_PACIENTES PRIMARY KEY (ID_PACIENTE),
    CONSTRAINT FK_PACIENTES_CLIENTES FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_PACIENTES_ESPECIES FOREIGN KEY (ID_ESPECIE) REFERENCES ESPECIES (ID_ESPECIE)
);

CREATE INDEX IX_USUARIOS_ID_ROL ON USUARIOS (ID_ROL);
CREATE INDEX IX_PACIENTES_ID_CLIENTE ON PACIENTES (ID_CLIENTE);
CREATE INDEX IX_PACIENTES_ID_ESPECIE ON PACIENTES (ID_ESPECIE);
